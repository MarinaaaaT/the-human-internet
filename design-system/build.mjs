// ---------- write ----------
function write(file, content, label) {
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`  ✓ ${label}: ${path.relative(ROOT, file) || file}`);
  } catch (e) {
    console.warn(`  ! skipped ${label}: ${e.message}`);
  }
}
const repoExists = (p) => fs.existsSync(p);

const designPath = path.join(DIR, "DESIGN.md");
const body = fs.readFileSync(designPath, "utf8").replace(/^---[\s\S]*?\n---\n?/, "");
const designMd = frontMatter() + "\n" + body.replace(/^\n*/, "\n");
const out = {
  css: css(),
  ts: ts(),
  swift: swift(),
  kt: kotlin(targets.android.package),
};

console.log("Design tokens →");
write(designPath, designMd, "DESIGN.md (master)");
const B = path.join(DIR, "build");
write(path.join(B, "web/tokens.css"), out.css, "build copy");
write(path.join(B, "ios/DesignTokens.swift"), out.swift, "build copy");
write(path.join(B, "android/DesignTokens.kt"), out.kt, "build copy");

write(path.join(ROOT, targets.web.tokensCss), out.css, "web tokens.css");
write(path.join(ROOT, targets.web.tokensTs), out.ts, "web tokens.ts");
write(path.join(ROOT, "DESIGN.md"), designMd, "web DESIGN.md");

if (process.argv.includes("--web-only")) {
  console.log("  - iOS and Android skipped (--web-only); copies are in design-system/build/");
  process.exit(0);
}

for (const [key, file, content] of [["ios", "tokensSwift", out.swift], ["android", "tokensKt", out.kt]]) {
  const repo = path.resolve(ROOT, targets[key].repo);
  if (!repoExists(repo)) { console.warn(`  ! ${key} repo not found at ${repo}; copy from design-system/build/${key}/ manually`); continue; }
  write(path.join(repo, targets[key][file]), content, `${key} tokens`);
  write(path.join(repo, "DESIGN.md"), designMd, `${key} DESIGN.md`);
}
